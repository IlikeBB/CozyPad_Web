let trustedCookies: Awaited<ReturnType<BrowserContext['cookies']>> = [];
async function loginTester(page: Page, context: BrowserContext, username = 'tester') {
  if (username === 'tester') await context.addCookies(trustedCookies);
  await page.goto('/');
  await page.getByLabel('帳號', { exact: true }).fill(username); await page.getByLabel('密碼', { exact: true }).fill('test-password');
  const response = page.waitForResponse(response => response.url().endsWith('/api/auth/login') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '登入', exact: true }).click();
  if ((await (await response).json()).challengeId) {
    await page.getByLabel('驗證碼', { exact: true }).fill(generateTotp('GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ'));
    await page.getByRole('button', { name: '驗證並登入' }).click();
  }
  await expect(page.getByRole('button', { name: 'Agents', exact: true })).toBeVisible();
  if (username === 'tester') trustedCookies = (await context.cookies()).filter(cookie => cookie.name === 'cozypad_tt_trust');
}

